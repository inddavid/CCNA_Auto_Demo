#!/usr/bin/env python3

"""A basic Python script that prints a greeting and performs a simple calculation."""


def main():
    name = "World"
    print(f"Hello, {name}!")

    a = 5
    b = 7
    total = a + b
    print(f"The sum of {a} and {b} is {total}.")


if __name__ == "__main__":
    main()
